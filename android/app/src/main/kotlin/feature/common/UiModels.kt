    fun zone(id: String): GuideZone = guideZones.firstOrNull { it.id == id } ?: guideZones.first()

    fun nextZone(id: String): GuideZone? {
        val currentIndex = guideZones.indexOfFirst { it.id == id }
        return guideZones.getOrNull(currentIndex + 1)
    }
